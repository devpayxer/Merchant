    and p_year between v.year_start and v.year_end
    and upper(v.make) = case
          when upper(p_make) in ('MERCEDES','MERCEDES-BENZ','MERCEDES BENZ') then 'MERCEDES-BENZ'
          when upper(p_make) in ('MINI','MINI COOPER') then 'MINI'
          when upper(p_make) in ('VW','VOLKSWAGEN') then 'VOLKSWAGEN'
          when upper(p_make) in ('CHEVY','CHEVROLET') then 'CHEVROLET'
          else upper(p_make)
        end
    and (
      replace(upper(v.model), ' AND ', ' & ') = upper(p_model)
      or upper(v.model) = replace(upper(p_model), ' & ', ' AND ')
      or upper(v.model) = upper(p_model)
      -- BMW: 328I -> 3 SERIES, 528XI -> 5 SERIES, 750LI -> 7 SERIES
      or (upper(v.make) = 'BMW'
          and upper(p_model) ~ '^[2357][0-9][0-9]'
          and upper(v.model) = left(upper(p_model), 1) || ' SERIES')
      -- Mercedes: C300 -> C-CLASS, E350 -> E-CLASS, S550 -> S-CLASS
      or (upper(v.make) = 'MERCEDES-BENZ'
          and upper(p_model) ~ '^[CES][0-9]{3}'
          and upper(v.model) = left(upper(p_model), 1) || '-CLASS')
      -- Dodge: RAM PICKUP (generico de la yarda) -> RAM 1500
      or (upper(v.make) = 'DODGE'
          and upper(p_model) = 'RAM PICKUP'
          and upper(v.model) = 'RAM 1500')
      -- Prefijos: SILVERADO -> SILVERADO 1500, ACCORD CROSSTOUR -> ACCORD
      or upper(p_model) like upper(v.model) || '%'
      or upper(v.model) like upper(p_model) || '%'
    )
  order by v.id
  limit 1
$$;

-- Combos para todo lo nuevo
insert into tracked_combos (vehicle_id, part_type_id)
select v.id, p.id
from vehicles v cross join part_types p
where v.active and p.active
on conflict do nothing;

-- Carriles re-balanceados (el catalogo paso de 170 a ~729 modelos):
--   1 = >= 10 carros vivos  (radar completo, ciclo ~3.6 dias)
--   2 = 3-9 carros vivos    (precio/competencia ~mensual)
--   3 = <= 2 carros vivos   (sin radar de eBay hasta el Growth Check;
--       la app igual muestra precios de yarda y el link de vendidos)
create or replace function refresh_yard_matches()
returns int language plpgsql as $$
declare n int;
begin
  update yard_inventory yi
  set matched_vehicle_id = match_vehicle(yi.make, yi.model, yi.year)
  where yi.left_at is null;
  get diagnostics n = row_count;

  update tracked_combos tc
  set priority = p.pri
  from (
    select tc2.id,
           case when coalesce(v.n, 0) >= 10 then 1
                when coalesce(v.n, 0) >= 3  then 2
                else 3 end as pri
    from tracked_combos tc2
    left join (
      select matched_vehicle_id as vid, count(*) as n
      from yard_inventory
      where left_at is null and matched_vehicle_id is not null
      group by 1
    ) v on v.vid = tc2.vehicle_id
  ) p
  where p.id = tc.id and tc.priority is distinct from p.pri;

  return n;
end $$;

select refresh_yard_matches();
